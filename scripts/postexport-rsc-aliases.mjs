import fs from "node:fs";
import path from "node:path";

const outDir = path.resolve(process.cwd(), process.argv[2] ?? "out");

if (!fs.existsSync(outDir)) {
  console.error(`[postexport-rsc-aliases] Missing export directory: ${outDir}`);
  process.exit(1);
}

function walkFiles(dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walkFiles(fullPath, acc);
    } else {
      acc.push(fullPath);
    }
  }
  return acc;
}

const txtFiles = walkFiles(outDir).filter((f) => f.endsWith(".txt"));
let created = 0;

function writeFileSafe(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
}

for (const filePath of txtFiles) {
  const rel = path.relative(outDir, filePath);
  const parts = rel.split(path.sep);

  const nextIdx = parts.findIndex((p) => p.startsWith("__next."));
  if (nextIdx === -1) {
    continue;
  }

  const prefix = parts[nextIdx];
  const tail = parts.slice(nextIdx + 1);

  // Skip already-flat files like __next.about.txt and __next._full.txt
  if (tail.length === 0) {
    continue;
  }

  const flatName = `${prefix}.${tail.join(".")}`;
  const targetRel = [...parts.slice(0, nextIdx), flatName].join(path.sep);
  const targetPath = path.join(outDir, targetRel);

  if (!fs.existsSync(targetPath)) {
    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.copyFileSync(filePath, targetPath);
    created += 1;
  }
}

// On some cPanel/Apache setups, inherited rules can deny /_next/static assets.
// Add explicit allow rules at the asset directories to avoid CSS/JS/font 403 errors.
const nextHtaccess = `# Auto-generated by postexport-rsc-aliases.mjs\n<IfModule mod_authz_core.c>\n  Require all granted\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Order allow,deny\n  Allow from all\n</IfModule>\n`;

const nextStaticHtaccess = `# Auto-generated by postexport-rsc-aliases.mjs\n<IfModule mod_authz_core.c>\n  Require all granted\n</IfModule>\n<IfModule !mod_authz_core.c>\n  Order allow,deny\n  Allow from all\n</IfModule>\n<IfModule mod_headers.c>\n  <FilesMatch "\\.(css|js|mjs|map|woff2?|ttf|otf|eot|svg|png|jpe?g|gif|webp|avif|ico)$">\n    Header set Cache-Control "public, max-age=31536000, immutable"\n  </FilesMatch>\n</IfModule>\n`;

writeFileSafe(path.join(outDir, "_next", ".htaccess"), nextHtaccess);
writeFileSafe(path.join(outDir, "_next", "static", ".htaccess"), nextStaticHtaccess);

// Mirror _next to assets/_next for hosts that block top-level /_next paths.
const nextDir = path.join(outDir, "_next");
const assetsNextDir = path.join(outDir, "assets", "_next");
if (fs.existsSync(nextDir)) {
  fs.rmSync(assetsNextDir, { recursive: true, force: true });
  fs.mkdirSync(path.dirname(assetsNextDir), { recursive: true });
  fs.cpSync(nextDir, assetsNextDir, { recursive: true });

  writeFileSafe(path.join(assetsNextDir, ".htaccess"), nextHtaccess);
  writeFileSafe(path.join(assetsNextDir, "static", ".htaccess"), nextStaticHtaccess);
}

console.log(`[postexport-rsc-aliases] Created ${created} alias file(s).`);
